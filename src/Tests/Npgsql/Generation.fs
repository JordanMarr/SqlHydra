// Read-only detection, from a column's pg_attribute row: (attgenerated, attidentity).

[<TestCase("s", "", true, Description = "GENERATED ALWAYS AS (...) STORED")>]
[<TestCase("v", "", true, Description = "GENERATED ALWAYS AS (...) VIRTUAL (PG18+)")>]
[<TestCase("", "a", true, Description = "GENERATED ALWAYS AS IDENTITY")>]
[<TestCase("", "d", false, Description = "GENERATED BY DEFAULT AS IDENTITY is writable")>]
[<TestCase("", "", false, Description = "an ordinary column")>]
let ``A column is read-only when the database generates it, and BY DEFAULT identity does not count`` attgenerated attidentity expected =
    let att : NpgsqlSchemaProvider.PgAttribute = { AttGenerated = attgenerated; AttIdentity = attidentity }
    NpgsqlSchemaProvider.isDatabaseGenerated att =! expected

// The write record, DB-free: drives SchemaTemplate.generate with a synthetic schema.

let private baseCfg : Config =
    {
        ConnectionString = ""
        OutputFile = ""
        Namespace = "TestNS"
        IsCLIMutable = true
        IsMutableProperties = false
        NullablePropertyType = NullablePropertyType.Option
        ProviderDbTypeAttributes = true
        TableDeclarations = true
        Readers = None
        Filters = Filters.Empty
        TypeMappingExtensions = []
    }

let private currencycode =
    {
        Column.Name = "currencycode"
        Column.IsNullable = false
        Column.IsPK = true
        Column.IsReadOnly = false
        Column.TypeMapping =
            {
                TypeMapping.ColumnTypeAlias = "character"
                TypeMapping.ClrType = "string"
                TypeMapping.DbType = System.Data.DbType.String
                TypeMapping.ProviderDbType = Some "Char"
            }
    }

let private name =
    { currencycode with
        Column.Name = "name"
        Column.IsPK = false }

/// A `GENERATED ALWAYS AS (...) STORED` column, as the schema provider marks it.
let private generatedRate =
    { currencycode with
        Column.Name = "rate"
        Column.IsPK = false
        Column.IsReadOnly = true
        Column.TypeMapping =
            {
                TypeMapping.ColumnTypeAlias = "numeric"
                TypeMapping.ClrType = "decimal"
                TypeMapping.DbType = System.Data.DbType.Decimal
                TypeMapping.ProviderDbType = Some "Numeric"
            } }

let private generateTable columns =
    let schema : Schema =
        {
            Tables =
                [ {
                    Table.Catalog = ""
                    Table.Schema = "sales"
                    Table.Name = "currency"
                    Table.Type = TableType.Table
                    Table.Columns = columns
                    Table.TotalColumns = List.length columns
                  } ]
            Enums = []
        }

    SchemaTemplate.generate baseCfg Provider.instance schema (Version.get()) []

/// `currency` with its two writable columns and the given ones.
let private generateColumns columns = generateTable (currencycode :: name :: columns)

/// The write record continues the read record's `type ... and ...` group, so that each may name the other.
let private writeRecordDeclaration (table: string) = $"and [<CLIMutable>] {table}_write ="

/// The generated code from the write record's declaration on.
let private writeRecordOf (table: string) (code: string) =
    match code.IndexOf(writeRecordDeclaration table) with
    | -1 -> failwith $"no write record for {table} in:\n{code}"
    | at -> code.Substring at

/// The generated code up to the write record's declaration: the read record and its members.
let private readRecordOf (table: string) (code: string) =
    match code.IndexOf(writeRecordDeclaration table) with
    | -1 -> code
    | at -> code.Substring(0, at)

[<Test>]
let ``A table with a read-only column gets a write record of the other columns``() =
    let writeRecord = generateColumns [ generatedRate ] |> writeRecordOf "currency"
    writeRecord.Contains("currencycode: string") =! true
    writeRecord.Contains("name: string") =! true
    writeRecord.Contains("rate: decimal") =! false

[<Test>]
let ``The write record implements IWriteOf of its read record``() =
    // This is what lets `writeEntity` refuse the read record and another table's write record.
    let writeRecord = generateColumns [ generatedRate ] |> writeRecordOf "currency"
    writeRecord.Contains("interface IWriteOf<currency>") =! true

[<Test>]
let ``The read record projects its writable columns onto the write record with ToWrite``() =
    let readRecord = generateColumns [ generatedRate ] |> readRecordOf "currency"
    readRecord.Contains("member this.ToWrite() : currency_write =") =! true
    readRecord.Contains("currencycode = this.currencycode") =! true
    readRecord.Contains("name = this.name") =! true
    readRecord.Contains("rate = this.rate") =! false

[<Test>]
let ``Every table record lists the columns it writes, so the query layer never reflects over it``() =
    let readRecord = generateColumns [] |> readRecordOf "currency"
    readRecord.Contains("interface IWriteColumns with") =! true
    readRecord.Contains("""{ WriteColumn.Name = "name"; Value = box this.name;""") =! true

[<Test>]
let ``The read record's write columns leave out the read-only column``() =
    let readRecord = generateColumns [ generatedRate ] |> readRecordOf "currency"
    readRecord.Contains("interface IHasWrite<currency_write> with") =! true
    readRecord.Contains("""{ WriteColumn.Name = "name"; Value = box this.name;""") =! true
    readRecord.Contains("""WriteColumn.Name = "rate";""") =! false

[<Test>]
let ``The write record lists the same columns``() =
    let writeRecord = generateColumns [ generatedRate ] |> writeRecordOf "currency"
    writeRecord.Contains("interface IWriteOf<currency> with") =! true
    writeRecord.Contains("""{ WriteColumn.Name = "currencycode"; Value = box this.currencycode;""") =! true
    writeRecord.Contains("""WriteColumn.Name = "rate";""") =! false

[<Test>]
let ``A table with no read-only column gets no write record``() =
    let code = generateColumns []
    code.Contains("_write") =! false
    code.Contains("IWriteOf") =! false

[<Test>]
let ``A table with no write record has no ToWrite``() =
    (generateColumns []).Contains("ToWrite") =! false

[<Test>]
let ``A table where every column is read-only gets no write record, since a record cannot be empty``() =
    let code = generateTable [ { currencycode with Column.IsReadOnly = true }; generatedRate ]
    code.Contains("_write") =! false

// Read-only detection against a live PostgreSQL: the four column kinds in one table, plus a
// writable `tax` in the same schema and another in a same-named table elsewhere. Drop either
// component from the lookup key and one of those decoys is silently marked read-only.

let private probeDdl =
    """
    DROP TABLE IF EXISTS sales.sqlhydra_readonly_probe;
    DROP TABLE IF EXISTS sales.sqlhydra_ordinary_probe;
    DROP TABLE IF EXISTS person.sqlhydra_readonly_probe;
    CREATE TABLE sales.sqlhydra_readonly_probe (
        id    int GENERATED ALWAYS AS IDENTITY,
        seq   int GENERATED BY DEFAULT AS IDENTITY,
        price numeric NOT NULL,
        tax   numeric GENERATED ALWAYS AS (price * 0.1) STORED
    );
    CREATE TABLE sales.sqlhydra_ordinary_probe (
        tax numeric NOT NULL
    );
    CREATE TABLE person.sqlhydra_readonly_probe (
        tax numeric NOT NULL
    );
    """

let private dropProbes =
    """
    DROP TABLE IF EXISTS sales.sqlhydra_readonly_probe;
    DROP TABLE IF EXISTS sales.sqlhydra_ordinary_probe;
    DROP TABLE IF EXISTS person.sqlhydra_readonly_probe;
    """

let private execute sql =
    use conn = new global.Npgsql.NpgsqlConnection(DB.connectionString)
    conn.Open()
    use cmd = new global.Npgsql.NpgsqlCommand(sql, conn)
    cmd.ExecuteNonQuery() |> ignore

[<Test>]
let ``The schema provider marks the columns PostgreSQL generates, and only those``() =
    execute probeDdl

    try
        let cfg =
            { baseCfg with
                ConnectionString = DB.connectionString
                Filters =
                    { Filters.Empty with
                        Includes =
                            [ "sales/sqlhydra_readonly_probe"
                              "sales/sqlhydra_ordinary_probe"
                              "person/sqlhydra_readonly_probe" ] } }

        let readOnly =
            (NpgsqlSchemaProvider.getSchema(cfg, false, [])).Tables
            |> List.collect (fun tbl ->
                tbl.Columns
                |> List.filter (fun col -> col.IsReadOnly)
                |> List.map (fun col -> ({ Schema = tbl.Schema; Table = tbl.Name; Column = col.Name } : NpgsqlSchemaProvider.ColumnRef)))
            |> Set.ofList

        // GENERATED ALWAYS AS IDENTITY and GENERATED ALWAYS AS (...) STORED; not `seq`
        // (GENERATED BY DEFAULT AS IDENTITY is writable), `price`, or either decoy `tax`.
        let expected : NpgsqlSchemaProvider.ColumnRef list =
            [ { Schema = "sales"; Table = "sqlhydra_readonly_probe"; Column = "id" }
              { Schema = "sales"; Table = "sqlhydra_readonly_probe"; Column = "tax" } ]
        readOnly =! set expected
    finally
        execute dropProbes
